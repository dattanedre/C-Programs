#include<stdio.h>
int main()
{


     //post increment
    int c=99;
    printf("%d\n",c++);
    printf("%d\n",c);
     
    //pre increment
    int b=10;
    printf("%d\n",++b);

    //post decrement
    int a=20;
    printf("%d\n",a--);
    printf("%d\n",a);

     //pre decrement
     int d=50;
    printf("%d\n",--d);


    

    return 0;
}